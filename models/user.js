const mongoose = require('mongoose');

// Definir la estructura (Schema) del usuario
const userSchema = new mongoose.Schema({
    username: { 
        type: String, 
        required: true, 
        unique: true,
        trim: true 
    },
    email: { 
        type: String, 
        required: true, 
        unique: true,
        lowercase: true,
        trim: true 
    },
    password: { 
        type: String, 
        required: true 
    },
    createdAt: { 
        type: Date, 
        default: Date.now 
    }
});

// Crear y exportar el modelo basado en el schema
const User = mongoose.model('User', userSchema);

module.exports = User;